import { chromium, expect } from '@playwright/test';
import { writeFile, mkdir } from 'node:fs/promises';
const base = process.argv[2] ?? 'https://cronista-arena.mangoocean-cf77f6f8.eastus2.azurecontainerapps.io';
const carpeta = 'docs/evidencia/interfaz-arena';
await mkdir(carpeta, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errores = []; page.on('pageerror', e => errores.push(e.message));
let id;
try {
  const catalogoRecibido = page.waitForResponse(r => r.url().endsWith('/api/arena/modelos'));
  await page.goto(`${base}/arena`);
  const catalogo = await (await catalogoRecibido).json();
  if (catalogo.modelos.length) await expect(page.getByRole('combobox', { name: 'Controller selection' })).toHaveValue('azar');
  await expect(page.getByRole('button', { name: 'Live', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('combobox', { name: 'Viewing mode' })).toHaveCount(0);
  await expect(page.getByRole('combobox', { name: 'Home formation', exact: true }).locator('option')).toHaveCount(13);
  expect(await page.locator('main').innerText()).not.toMatch(/Near.live|Casi en vivo/i);
  await page.getByRole('combobox', { name: 'Controller selection' }).selectOption('programado');
  await page.getByRole('combobox', { name: 'Home formation', exact: true }).selectOption('5-3-2');
  await page.getByRole('combobox', { name: 'Away formation', exact: true }).selectOption('4-2-2-2');
  await page.screenshot({ path: `${carpeta}/configuracion-publica.png` });
  const creada = page.waitForResponse(r => r.url().endsWith('/api/arena/sesiones') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Start live match', exact: true }).click();
  const respuesta = await creada; expect(respuesta.status()).toBe(201);
  id = (await respuesta.json()).id;
  const payload = respuesta.request().postDataJSON(); expect(payload.presentacion).toBe('buffer');
  expect(payload.local).toBe('5-3-2'); expect(payload.visita).toBe('4-2-2-2');
  await expect(page.getByTestId('arena-buffer-status')).toContainText('Live', { timeout: 30000 });
  await expect.poll(async () => await page.getByTestId('arena-live-text').locator('[data-event-tick]').count()).toBeGreaterThan(0);
  await page.getByRole('button', { name: 'Pause broadcast', exact: true }).click();
  const clock = await page.getByTestId('arena-clock').textContent();
  await page.waitForTimeout(300); await expect(page.getByTestId('arena-clock')).toHaveText(clock);
  const panel = page.getByTestId('arena-companion');
  await expect(panel.getByTestId('arena-buffer')).toBeVisible();
  await expect(panel.getByRole('region', { name: 'Verified commentary' })).toBeAttached();
  await page.locator('#arena-watch').evaluate(e => e.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: `${carpeta}/en-vivo-publico.png` });
  await page.getByRole('button', { name: 'Switch to Spanish' }).click();
  await page.setViewportSize({ width: 360, height: 780 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
  await page.getByTestId('arena-buffer').scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${carpeta}/movil-publico.png` });
  await page.getByRole('button', { name: 'Cancelar partido en vivo', exact: true }).click();
  await expect(page.getByTestId('arena-live-status')).toHaveText('Partido cancelado');
  await page.getByRole('button', { name: 'Partidos guardados', exact: true }).click();
  await page.getByRole('button', { name: 'Cargar duelo de modelos grabado', exact: true }).click();
  await expect(page.locator('.arena-controller')).toContainText(['cronista-equilibrado', 'cronista-rapido']);
  await expect(page.getByTestId('arena-clock')).toHaveText('0:00 / 1:00');
  await expect(page.getByTestId('arena-companion').getByTestId('arena-narration')).toBeVisible();
  expect(errores).toEqual([]);
  await writeFile(`${carpeta}/navegador-publico.json`, JSON.stringify({ checkedUtc: new Date().toISOString(), url: `${base}/arena`, phase: 'passed', match: id, initial: 'live', presentation: payload.presentacion, formationOptions: 12, home: payload.local, away: payload.visita, randomSeed: payload.seed, textNarrationWithAudioOff: true, audioControlsBesidePitch: true, pause: true, savedRecording: true, mobileWidth: 360, horizontalOverflow: false, javascriptErrors: errores, inference: false, speechSynthesis: false }, null, 2) + '\n');
  console.log(JSON.stringify({ phase: 'passed', evidence: `${carpeta}/navegador-publico.json` }));
} finally {
  if (id) await page.request.delete(`${base}/api/arena/sesiones/${id}`).catch(() => {});
  await browser.close();
}
