// Material de montaje con datos reales; no modifica el DOM ni las respuestas.
import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { chromium } from "@playwright/test";

const base = process.argv[2];
if (!base) throw new Error("Uso: npm run capture:demo -- http://127.0.0.1:3418");
const out = resolve(".cache/demo-recording");
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: out, size: { width: 1440, height: 900 } } });
const page = await context.newPage();
const errors = [];
const scenes = [];
page.on("pageerror", error => errors.push(error.message));
const started = Date.now();
async function shot(name) {
  await page.screenshot({ path: resolve(out, `${name}.png`) });
  scenes.push({ name, elapsedMs: Date.now() - started, url: page.url() });
}
try {
  await page.goto(base, { waitUntil: "networkidle", timeout: 240_000 });
  await page.getByTestId("sentence").first().waitFor();
  const writer = await page.getByTestId("llm-label").innerText();
  assert.match(writer, /Microsoft Foundry|azure-openai/);
  assert.doesNotMatch(writer, /Offline stub|Rehearsal fixture/);
  assert.equal(await page.getByTestId("llm-label").getAttribute("data-fixture"), "false");
  assert.equal(await page.getByTestId("verify-bar").getAttribute("data-mode"), "llm");
  const verification = await page.getByTestId("verify-bar").innerText();
  await shot("01-home");
  await page.waitForTimeout(2000);
  await page.getByTestId("sentence").first().getByTestId("sentence-text").click();
  await page.locator('[data-testid="timeline-event"][data-highlighted="true"]').first().waitFor();
  await shot("02-evidence");
  await page.waitForTimeout(2500);
  await page.getByTestId("open-process").click();
  await page.getByTestId("process-view").waitFor();
  await shot("03-process");
  await page.waitForTimeout(3000);
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByTestId("lang-toggle").locator('[data-lang="es"]').click();
  await shot("04-spanish");
  await page.waitForTimeout(2000);
  await page.getByTestId("lang-toggle").locator('[data-lang="en"]').click();
  await page.getByTestId("mode-toggle").locator('[data-mode="analista"]').click();
  await shot("05-analyst");
  await page.waitForTimeout(2500);
  await page.getByTestId("mode-toggle").locator('[data-mode="aficionado"]').click();
  const goal = page.locator('[data-testid="timeline-event"][data-tipo="gol"]').first();
  await goal.scrollIntoViewIfNeeded();
  await goal.click();
  await page.getByTestId("goal-card").waitFor();
  await shot("06-goal-2d");
  await page.waitForTimeout(2500);
  await page.getByTestId("pitch-3d-btn").click();
  await page.getByTestId("pitch-3d-canvas").waitFor({ timeout: 20_000 });
  await page.waitForTimeout(3000);
  await shot("07-goal-3d");
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByTestId("data-link").click();
  await page.getByTestId("data-page").waitFor();
  await shot("08-dataset");
  await page.waitForTimeout(2500);
  assert.deepEqual(errors, [], "No debe haber errores de JavaScript en la grabación.");
  const mobile = await browser.newContext({ viewport: { width: 360, height: 800 }, isMobile: true, deviceScaleFactor: 1 });
  const phone = await mobile.newPage();
  await phone.goto(base, { waitUntil: "networkidle", timeout: 240_000 });
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "La home no debe desbordar a 360px.");
  await phone.screenshot({ path: resolve(out, "09-mobile.png"), fullPage: true });
  await mobile.close();
  const cards = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  const card = await cards.newPage();
  await card.goto(new URL("../docs/entrega/tarjetas-video.html", import.meta.url).href);
  for (const id of ["architecture", "evaluation"]) await card.locator(`#${id}`).screenshot({ path: resolve(out, `${id}.png`) });
  await cards.close();
  await context.close();
  const video = await page.video().path();
  const manifest = { recordedUtc: new Date().toISOString(), base, writer, verification, video, scenes, viewport: { width: 1440, height: 900 }, mobileWidth: 360, pageErrors: errors, note: "Local real-model screencast; no narration, edits or public-hosting claim. Cache status is visible in the footer." };
  writeFileSync(resolve(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  console.log(JSON.stringify(manifest, null, 2));
} finally { await context.close(); await browser.close(); }
